const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('duo', {
  checkUpdate: () => ipcRenderer.invoke('duo:update:check'),
  downloadUpdate: () => ipcRenderer.invoke('duo:update:download'),
  bootstrap: () => ipcRenderer.invoke('duo:bootstrap'),
  connections: () => ipcRenderer.invoke('duo:connections'),
  pickProject: () => ipcRenderer.invoke('duo:project'),
  library: () => ipcRenderer.invoke('duo:library'),
  createWorkspace: (name) => ipcRenderer.invoke('duo:workspace:create', name),
  activateProject: (value) => ipcRenderer.invoke('duo:library:activate', value),
  patchRecord: (value) => ipcRenderer.invoke('duo:library:patch', value),
  pickParent: () => ipcRenderer.invoke('duo:project:parent'),
  createProject: (value) => ipcRenderer.invoke('duo:project:create', value),
  relinkProject: (id) => ipcRenderer.invoke('duo:project:relink', id),
  githubRepos: () => ipcRenderer.invoke('duo:github:repos'),
  cloneProject: (value) => ipcRenderer.invoke('duo:project:clone', value),
  createWorktree: (value) => ipcRenderer.invoke('duo:project:worktree', value),
  cancelProjectOperation: () => ipcRenderer.invoke('duo:project:cancel'),
  settings: (config) => ipcRenderer.invoke('duo:settings', config),
  newSession: () => ipcRenderer.invoke('duo:new'),
  activateSession: (id) => ipcRenderer.invoke('duo:session:activate', id),
  patchSession: (value) => ipcRenderer.invoke('duo:session:patch', value),
  skillDetail: (id) => ipcRenderer.invoke('duo:skill:detail', id),
  createSkill: (value) => ipcRenderer.invoke('duo:skill:create', value),
  updateSkill: (value) => ipcRenderer.invoke('duo:skill:update', value),
  revealSkill: (id) => ipcRenderer.invoke('duo:skill:reveal', id),
  importSkill: () => ipcRenderer.invoke('duo:skill:import'),
  run: (payload) => ipcRenderer.invoke('duo:run', payload),
  schedule: (value) => ipcRenderer.invoke('duo:schedule:create', value),
  cancelSchedule: (id) => ipcRenderer.invoke('duo:schedule:cancel', id),
  memory: () => ipcRenderer.invoke('duo:memory:list'),
  previewMemory: (value) => ipcRenderer.invoke('duo:memory:preview', value),
  pickMemoryFile: () => ipcRenderer.invoke('duo:memory:file'),
  importMemory: (value) => ipcRenderer.invoke('duo:memory:import', value),
  exportMemory: (value) => ipcRenderer.invoke('duo:memory:export', value),
  usage: () => ipcRenderer.invoke('duo:usage'),
  quota: () => ipcRenderer.invoke('duo:quota'),
  saveMemory: (value) => ipcRenderer.invoke('duo:memory:save', value),
  deleteMemory: (value) => ipcRenderer.invoke('duo:memory:delete', value),
  stop: () => ipcRenderer.invoke('duo:stop'),
  listFiles: (value) => ipcRenderer.invoke('duo:files:list', value),
  searchFiles: (value) => ipcRenderer.invoke('duo:files:search', value),
  readFile: (value) => ipcRenderer.invoke('duo:files:read', value),
  saveFile: (value) => ipcRenderer.invoke('duo:files:save', value),
  editorDirty: (count) => ipcRenderer.invoke('duo:editor:dirty', count),
  git: () => ipcRenderer.invoke('duo:git'),
  commit: (payload) => ipcRenderer.invoke('duo:commit', payload),
  push: () => ipcRenderer.invoke('duo:push'),
  remote: () => ipcRenderer.invoke('duo:remote'),
  reveal: () => ipcRenderer.invoke('duo:reveal'),
  copy: (text) => ipcRenderer.invoke('duo:copy', text),
  openUrl: (value) => ipcRenderer.invoke('duo:link', value),
  export: (id) => ipcRenderer.invoke('duo:export', id),
  window: (action) => ipcRenderer.invoke('duo:window', action),
  onEvent: (callback) => {
    const handler = (_event, data) => callback(data);
    ipcRenderer.on('duo:event', handler);
    return () => ipcRenderer.removeListener('duo:event', handler);
  },
});
